// WP-06 view generator: graph → data/views/, the only bridge between the
// graph and the screens (R11). One view JSON per country subject in the graph,
// plus index.json and census.json.
//
//   R1  no instance literals: the country set, names, ids and dates all come
//       from graph rows; nothing here names a country.
//   R2  vocabulary (states, doc types) comes from engine/generated only.
//   R4  no verdicts: every row carries the graph's own epistemic state.
//   R5  publish blocking: every view is validated before anything is written;
//       one unresolved value aborts the whole run with exit 1 and no output.
//   R6  every figure a view carries is a graph value or a census key that the
//       honesty tests recompute from the view rows.
//   AD-8 the graph is read through engine/reader/reader.mjs alone.
//
// Determinism: output depends only on data/graph bytes. as_of and build_id
// come from build.json; no wall clock, no randomness, stable ordering.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readGraph, LEDGER_REL } from '../reader/reader.mjs';

function arg(name, dflt) {
  const i = process.argv.indexOf(name);
  return i !== -1 && process.argv[i + 1] ? resolve(process.argv[i + 1]) : dflt;
}
const root = arg('--root', resolve(dirname(fileURLToPath(import.meta.url)), '..', '..'));
const outDir = arg('--out', join(root, 'data', 'views'));

function fail(msgs) {
  for (const m of [].concat(msgs)) console.error(`views: ${m}`);
  console.error('views: publish blocked — nothing written (R5)');
  process.exit(1);
}

// ---------------------------------------------------------------- inputs
const g = readGraph(root);
if (g === null) fail('no published graph — run the builder first');
if (g.build === null) fail('the graph carries no build.json — run the builder first');
if (g.census === null) fail('the graph carries no census.json — run the builder first');
const asOf = String(g.build.built_at ?? '').slice(0, 10);
const buildId = g.build.build_id ?? '';
if (!/^[0-9a-f]{64}$/.test(buildId) || asOf.length !== 10) fail('build.json carries no usable build_id/built_at');

const vocab = JSON.parse(readFileSync(join(root, 'engine', 'generated', 'vocab.json'), 'utf8'));
const STATES = (vocab.facet_values?.['FACET-EPISTEMIC-STATE'] ?? []).map((s) => String(s).toLowerCase());
const DOC_TYPES = (vocab.facet_values?.['FACET-DOC-TYPE'] ?? []).map((s) => String(s).toLowerCase());
const docType = (v) => {
  if (!DOC_TYPES.includes(v)) throw new Error(`doc type "${v}" is not in the generated vocabulary (R2)`);
  return v;
};

// Any state outside the generated vocabulary anywhere in the graph blocks the
// whole run — a view built over it would launder the bogus state into screens.
{
  const bad = [];
  for (const [f, rows] of [['base.csv', g.base], ['derived.csv', g.derived]]) {
    for (const r of rows) {
      if (!STATES.includes(r.state)) bad.push(`${f} ${r.iso3} ${r.record_key}: state "${r.state}" is not in the generated vocabulary`);
    }
  }
  if (bad.length > 0) fail(bad);
}

// ---------------------------------------------------------------- copy
// Fixed label text. Labels and headings only — every figure, date, id and
// name in a view is a graph value.
const STRIP_HEADING = 'What this runtime has read so far';
const STRIP_NOTE = "Unknown and absent describe this runtime's reading, not the country.";
const NEXT_DATE_REASON = 'No deadline source is on record in this runtime yet; a date shown here would be invented.';
const FILE_SCOPE =
  'File-level receipt: the bytes are hashed, but no page or sentence anchors are held, so none of this document’s internal figures appear on these screens.';
const REGISTRY_SCOPE =
  'Registry entry only: the registry dataset asserts this title and date; no document bytes are held under this row.';
const BTR_SCOPE =
  'Listing only: the submissions listing shows a report under this party folder; the report bytes are not held by this runtime.';
const CONTRACT =
  'R11: screens read this view JSON and census.json only — never seeds or engine internals. ' +
  'Generated by engine/views/generate.mjs from the published graph; every value is traceable to a graph row, ' +
  'and every count is recomputable from the rows (census keys).';

// ---------------------------------------------------------------- helpers
const CODE_RE = /^[A-Z]{3}$/; // pattern, not an instance literal (R1)
const bestState = (rows) => rows.slice().sort((a, b) => STATES.indexOf(a.state) - STATES.indexOf(b.state))[0];
const CELL_RE = /^page (\d+), row: (.+)$/s;

function parseQuote(row, reading) {
  const m = row ? CELL_RE.exec(row.anchor_locator) : null;
  if (!m) return null;
  return { page: Number(m[1]), text: m[2], reading };
}

function urlTitle(url) {
  const tail = url.split('/').pop() ?? '';
  try {
    return decodeURIComponent(tail) || url;
  } catch {
    return tail || url;
  }
}

const emptyRow = {
  size_bytes: null,
  pages: null,
  quote: null,
  refusal: null,
  receipt_scope: null,
  provenance: [],
};

// ---------------------------------------------------------------- assembly
const byCountry = new Map();
for (const r of g.base) {
  if (!CODE_RE.test(r.iso3)) continue; // headers and unresolved spellings are not country views
  if (!byCountry.has(r.iso3)) byCountry.set(r.iso3, []);
  byCountry.get(r.iso3).push(r);
}

function buildView(iso3, rows) {
  const byKey = new Map(rows.map((r) => [r.record_key, r]));

  // -- country name: the first spelling the graph itself records.
  const fromCell = (() => {
    for (const r of rows.slice().sort((a, b) => (a.record_key < b.record_key ? -1 : 1))) {
      const m = CELL_RE.exec(r.anchor_locator ?? '');
      if (m) return m[2].split('|')[0].trim();
    }
    return '';
  })();
  const btrListed = rows.find((r) => /^btr\.folder\..+\.listed$/.test(r.record_key));
  const name_en = byKey.get('ndc.registry.listed')?.value || fromCell || btrListed?.value || iso3;

  const viewRows = [];
  const treatyStatus = [];

  // -- treaty status lists (one document row per treaty read for this country)
  const treaties = [...new Set(rows.map((r) => /^treaty\.([^.]+)\./.exec(r.record_key)?.[1]).filter(Boolean))].sort();
  for (const t of treaties) {
    const sig = byKey.get(`treaty.${t}.signature.date`);
    const act = byKey.get(`treaty.${t}.action.date`);
    const kind = byKey.get(`treaty.${t}.action.kind`);
    const parts = [sig, act, kind].filter(Boolean);
    const events = [];
    if (sig?.state === 'observed' && sig.value) events.push({ label: 'signature', date: sig.value, display: sig.value });
    if (act?.state === 'observed' && act.value) {
      events.push({ label: (kind?.state === 'observed' && kind.value) || 'action', date: act.value, display: act.value });
    }
    const reading = events.map((e) => `${e.label} ${e.date}`).join(', ');
    const quote = parseQuote(act ?? sig ?? kind, reading || 'no event observed in this row');
    const spine = bestState(parts);
    const doc_id = `untc-${t}`;
    viewRows.push({
      ...emptyRow,
      doc_id,
      title: `UN Treaty Collection status list (${t})`,
      doc_type: docType('treaty-status-list'),
      date: '',
      source_url: '',
      sha256: spine.anchor_sha256 ?? '',
      official_english: 'unknown',
      state: spine.state,
      state_reason: spine.state === 'observed' ? '' : spine.reason,
      quote,
    });
    if (quote && events.length > 0) {
      treatyStatus.push({ treaty_label: t, events, receipt: doc_id });
    }
  }

  // -- the registry's latest-submission entry
  const regTitle = byKey.get('ndc.registry.latest.title');
  const regDate = byKey.get('ndc.registry.latest.date');
  if (regTitle || regDate) {
    const spine = bestState([regTitle, regDate].filter(Boolean));
    viewRows.push({
      ...emptyRow,
      doc_id: 'ndc-registry-latest',
      title: regTitle?.value || 'registry entry (untitled)',
      doc_type: docType('ndc'),
      date: regDate?.value ?? '',
      source_url: '',
      sha256: '',
      official_english: 'unknown',
      state: spine.state,
      state_reason: spine.state === 'observed' ? '' : spine.reason,
      receipt_scope: spine.state === 'observed' ? REGISTRY_SCOPE : null,
      provenance: [spine.anchor_locator].filter(Boolean),
    });
  }

  // -- indexed documents (bytes held, or honestly not)
  for (const r of rows.filter((x) => x.record_key.startsWith('ndc.document.')).sort((a, b) => (a.record_key < b.record_key ? -1 : 1))) {
    const slugId = r.record_key.slice('ndc.document.'.length);
    const held = r.state === 'observed' && /^[0-9a-f]{64}$/.test(r.value);
    const keyM = /^index row key=(.+)$/.exec(r.anchor_locator ?? '');
    viewRows.push({
      ...emptyRow,
      doc_id: `doc-${slugId}`,
      title: held ? urlTitle(r.anchor_locator) : keyM?.[1] || slugId,
      doc_type: docType('ndc'),
      date: '',
      source_url: held ? r.anchor_locator : '',
      sha256: held ? r.value : '',
      official_english: 'unknown',
      state: r.state,
      state_reason: r.state === 'observed' ? '' : r.reason,
      receipt_scope: held ? FILE_SCOPE : null,
    });
  }

  // -- transparency-report folders from the submissions listing
  const folders = new Map();
  for (const r of rows) {
    const m = /^btr\.folder\.([^.]+)\.(.+)$/.exec(r.record_key);
    if (!m) continue;
    if (!folders.has(m[1])) folders.set(m[1], []);
    folders.get(m[1]).push({ tail: m[2], row: r });
  }
  for (const f of [...folders.keys()].sort()) {
    const parts = folders.get(f);
    const listed = parts.find((p) => p.tail === 'listed');
    if (!listed) continue;
    const submitted = parts.filter((p) => p.tail.endsWith('.submitted')).sort((a, b) => (a.tail < b.tail ? -1 : 1));
    const held = submitted.filter((p) => p.row.state === 'observed' && p.row.value === 'true');
    const unknowns = parts.filter((p) => p.row.state !== 'observed').sort((a, b) => (a.tail < b.tail ? -1 : 1));
    const observedHere = held.length > 0;
    viewRows.push({
      ...emptyRow,
      doc_id: `btr-${f}`,
      title: listed.row.value,
      doc_type: docType('btr'),
      date: '',
      source_url: '',
      sha256: '',
      official_english: 'unknown',
      state: observedHere ? 'observed' : 'unknown',
      state_reason: observedHere ? '' : unknowns[0]?.row.reason || 'the listing shows this folder with no readable report entry',
      receipt_scope: observedHere ? BTR_SCOPE : null,
      provenance: held.map((p) => p.row.anchor_locator),
    });
  }

  // -- country seed ledger documents (spine + per-field rows from the builder)
  const fields = new Map(); // doc_id -> { col: value }
  for (const r of rows) {
    if (!r.record_key.startsWith('ledger-field.')) continue;
    const rest = r.record_key.slice('ledger-field.'.length);
    const cut = rest.lastIndexOf('.');
    const docId = rest.slice(0, cut);
    const col = rest.slice(cut + 1);
    if (!fields.has(docId)) fields.set(docId, {});
    fields.get(docId)[col] = r.value;
  }
  const spines = rows.filter((r) => r.record_key.startsWith('ledger.')).sort((a, b) => (a.record_key < b.record_key ? -1 : 1));
  for (const r of spines) {
    const docId = r.record_key.slice('ledger.'.length);
    const f = fields.get(docId) ?? {};
    const note = f.note ?? '';
    // Citation syntax in the ledger note: row p.<n> "<cell text>" = <reading>.
    const qm = /row p\.(\d+)\s+"([^"]+)"\s+=\s+([^."]+)\./.exec(note);
    const quote = qm ? { page: Number(qm[1]), text: qm[2], reading: qm[3].trim() } : null;
    const rm = /refused:\s*"([^"]+)"/i.exec(r.reason ?? '');
    viewRows.push({
      doc_id: docId,
      title: r.value,
      doc_type: f.doc_type ?? '',
      date: f.date ?? '',
      source_url: f.source_url ?? '',
      sha256: f.sha256 ?? '',
      size_bytes: f.size_bytes ? Number(f.size_bytes) : null,
      pages: f.pages ? Number(f.pages) : null,
      official_english: f.official_english ?? 'unknown',
      state: r.state,
      state_reason: r.reason ?? '',
      quote,
      refusal: rm ? rm[1] : null,
      receipt_scope: r.state === 'observed' && f.sha256 && !quote ? FILE_SCOPE : null,
      provenance: note ? note.split(/(?<=\.)\s+/).filter(Boolean) : [],
    });
  }

  return {
    view: 'country-ledger',
    contract: CONTRACT,
    as_of: asOf,
    build_id: buildId,
    country: { iso3, name_en },
    treaty_status: treatyStatus,
    next_date: { date: null, label: null, receipt: null, state: 'unknown', reason: NEXT_DATE_REASON },
    strip: {
      heading: STRIP_HEADING,
      note: STRIP_NOTE,
      segments: STATES.map((s) => ({ label: s === 'observed' ? 'evidenced' : s, state: s, census_key: `states_${s}` })),
    },
    rows: viewRows,
  };
}

// ---------------------------------------------------------------- counts
const COUNT_KEYS = ['documents_on_record', 'documents_with_bytes', 'documents_without_bytes', 'source_urls_recorded', ...STATES.map((s) => `states_${s}`)];
function countsOf(viewRows) {
  const c = Object.fromEntries(COUNT_KEYS.map((k) => [k, 0]));
  c.documents_on_record = viewRows.length;
  for (const r of viewRows) {
    c[r.sha256 ? 'documents_with_bytes' : 'documents_without_bytes']++;
    if (r.source_url) c.source_urls_recorded++;
    c[`states_${r.state}`]++;
  }
  return c;
}
const DERIVATIONS = {
  documents_on_record: 'rows in the view ledger(s) this census covers',
  documents_with_bytes: 'view rows whose sha256 is non-empty',
  documents_without_bytes: 'view rows whose sha256 is empty',
  source_urls_recorded: 'view rows whose source_url is non-empty',
  ...Object.fromEntries(STATES.map((s) => [`states_${s}`, `view rows with state = ${s}`])),
};

// ---------------------------------------------------------------- validate
function validate(view) {
  const p = [];
  const where = view.country.iso3;
  if (!CODE_RE.test(view.country.iso3)) p.push(`${where}: country.iso3 is not a party code`);
  if (!view.country.name_en) p.push(`${where}: country has no recorded name`);
  const ids = new Set();
  for (const r of view.rows) {
    const at = `${where} ${r.doc_id}`;
    if (!r.doc_id) p.push(`${where}: a row has no doc_id`);
    if (ids.has(r.doc_id)) p.push(`${at}: duplicate doc_id`);
    ids.add(r.doc_id);
    for (const k of ['title', 'doc_type', 'date', 'source_url', 'sha256', 'official_english', 'state', 'state_reason']) {
      if (typeof r[k] !== 'string') p.push(`${at}: ${k} is not a string`);
    }
    for (const k of ['size_bytes', 'pages']) {
      if (r[k] !== null && !Number.isInteger(r[k])) p.push(`${at}: ${k} is neither null nor an integer`);
    }
    if (!STATES.includes(r.state)) p.push(`${at}: state "${r.state}" is not in the generated vocabulary`);
    if ((r.state === 'unknown' || r.state === 'absent') && !r.state_reason) p.push(`${at}: state ${r.state} carries no reason`);
    if (r.quote !== null) {
      if (!Number.isInteger(r.quote.page) || r.quote.page < 1 || !r.quote.text || !r.quote.reading) {
        p.push(`${at}: malformed quote`);
      }
    }
    if (r.refusal !== null && !r.state_reason.includes(r.refusal)) p.push(`${at}: refusal is not verbatim from state_reason`);
    if (!Array.isArray(r.provenance)) p.push(`${at}: provenance is not a list`);
  }
  for (const t of view.treaty_status) {
    const row = view.rows.find((r) => r.doc_id === t.receipt);
    if (!row || !row.quote) {
      p.push(`${where} ${t.treaty_label}: treaty status cites receipt "${t.receipt}" which has no quote`);
      continue;
    }
    for (const ev of t.events) {
      if (!row.quote.reading.includes(ev.date)) p.push(`${where} ${t.treaty_label}: event date ${ev.date} missing from quote reading`);
      if (!row.quote.text.includes(ev.display)) p.push(`${where} ${t.treaty_label}: display "${ev.display}" missing from quote text`);
    }
  }
  const nd = view.next_date;
  if (!STATES.includes(nd.state)) p.push(`${where}: next_date state is not vocabulary`);
  if (nd.date === null && !nd.reason) p.push(`${where}: empty next_date carries no reason`);
  if (nd.date !== null && (!nd.label || !view.rows.some((r) => r.doc_id === nd.receipt))) {
    p.push(`${where}: a shown next date must carry a label and a receipt row in this view`);
  }
  for (const s of view.strip.segments) {
    if (!(s.census_key in DERIVATIONS)) p.push(`${where}: strip segment "${s.label}" counts via unknown census key ${s.census_key}`);
  }
  return p;
}

// ---------------------------------------------------------------- run
const views = [...byCountry.keys()].sort().map((iso3) => buildView(iso3, byCountry.get(iso3)));
const problems = views.flatMap(validate);
if (problems.length > 0) fail(problems.slice(0, 50).concat(problems.length > 50 ? [`… and ${problems.length - 50} more`] : []));

const index = {
  as_of: asOf,
  build_id: buildId,
  countries: views.map((v) => ({
    iso3: v.country.iso3,
    name_en: v.country.name_en,
    ledger: LEDGER_REL,
    counts: countsOf(v.rows),
  })),
};
const worldCounts = Object.fromEntries(COUNT_KEYS.map((k) => [k, index.countries.reduce((n, c) => n + c.counts[k], 0)]));
const census = {
  as_of: asOf,
  build_id: buildId,
  ledger: LEDGER_REL,
  counts: worldCounts,
  derivations: DERIVATIONS,
  graph: g.census,
  graph_note:
    'graph-level counters copied verbatim from the published graph census; the r6-census-fresh gate recomputes every one of them from the graph CSVs on each run',
};

// All views validated — only now does anything touch disk (R5).
rmSync(join(outDir, 'countries'), { recursive: true, force: true });
mkdirSync(join(outDir, 'countries'), { recursive: true });
const writeJSON = (p, o) => writeFileSync(p, JSON.stringify(o, null, 2) + '\n');
for (const v of views) writeJSON(join(outDir, 'countries', `${v.country.iso3.toLowerCase()}.json`), v);
writeJSON(join(outDir, 'index.json'), index);
writeJSON(join(outDir, 'census.json'), census);
console.log(
  `views: ${views.length} countries, ${views.reduce((n, v) => n + v.rows.length, 0)} rows, ` +
    `${views.reduce((n, v) => n + v.treaty_status.length, 0)} treaty lines, build ${buildId.slice(0, 12)}`,
);
